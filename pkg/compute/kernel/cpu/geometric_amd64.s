//go:build amd64

#include "textflag.h"

// =========================================================================
// geometricFrame: AMD64 SSE2 PGA lane.
//
// func geometricFrame(value *uint64, opcode uint64) bool
//
// The Boolean CPU backend already targets AVX2 for bitwise hot loops. The
// PGA product is sparse enough that scalar SSE2 keeps the dependency graph
// explicit; reverse/sign-flip phases use packed SSE2 lanes.
// =========================================================================
TEXT ·geometricFrame(SB), NOSPLIT, $128-17
	MOVQ	value+0(FP), DI
	MOVQ	opcode+8(FP), AX

	ANDQ	$0xF0, AX

	CMPQ	AX, $0x10
	JE	geom_compose

	CMPQ	AX, $0x20
	JE	geom_sandwich

	CMPQ	AX, $0x30
	JE	geom_reverse

	MOVB	$0, ret+16(FP)
	RET

geom_compose:
	LEAQ	320(DI), SI
	LEAQ	384(DI), DX
	LEAQ	256(DI), R8
	CALL	·geometricProductStore(SB)
	MOVB	$1, ret+16(FP)
	RET

geom_sandwich:
	LEAQ	320(DI), SI
	LEAQ	384(DI), DX
	LEAQ	tmp-128(SP), R8
	CALL	·geometricProductStore(SB)

	LEAQ	rev-64(SP), DX
	MOVQ	$0x8000000000000000, R9
	PXOR	X8, X8
	MOVQ	R9, X9
	PUNPCKLQDQ X9, X9
	PXOR	X10, X10
	MOVQ	R9, X11
	PUNPCKLQDQ X11, X10
	PXOR	X12, X12
	MOVQ	R9, X13
	PUNPCKLQDQ X12, X13

	MOVOU	384(DI), X0
	PXOR	X10, X0
	MOVOU	X0, 0(DX)
	MOVOU	400(DI), X0
	PXOR	X9, X0
	MOVOU	X0, 16(DX)
	MOVOU	416(DI), X0
	PXOR	X9, X0
	MOVOU	X0, 32(DX)
	MOVOU	432(DI), X0
	PXOR	X13, X0
	MOVOU	X0, 48(DX)

	LEAQ	tmp-128(SP), SI
	LEAQ	256(DI), R8
	CALL	·geometricProductStore(SB)

	MOVB	$1, ret+16(FP)
	RET

geom_reverse:
	MOVQ	$0x8000000000000000, R9
	PXOR	X8, X8
	MOVQ	R9, X9
	PUNPCKLQDQ X9, X9
	PXOR	X10, X10
	MOVQ	R9, X11
	PUNPCKLQDQ X11, X10
	PXOR	X12, X12
	MOVQ	R9, X13
	PUNPCKLQDQ X12, X13

	MOVOU	320(DI), X0
	PXOR	X10, X0
	MOVOU	X0, 256(DI)
	MOVOU	336(DI), X0
	PXOR	X9, X0
	MOVOU	X0, 272(DI)
	MOVOU	352(DI), X0
	PXOR	X9, X0
	MOVOU	X0, 288(DI)
	MOVOU	368(DI), X0
	PXOR	X13, X0
	MOVOU	X0, 304(DI)

	MOVB	$1, ret+16(FP)
	RET

TEXT ·geometricProductStore(SB), NOSPLIT|NOFRAME, $0
	// out[0] = l0*r0 - l4*r4 - l5*r5 - l6*r6
	MOVSD	0(SI), X0
	MULSD	0(DX), X0
	MOVSD	32(SI), X1
	MULSD	32(DX), X1
	SUBSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	40(DX), X1
	SUBSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	48(DX), X1
	SUBSD	X1, X0
	MOVSD	X0, 0(R8)

	// out[1]
	MOVSD	0(SI), X0
	MULSD	8(DX), X0
	MOVSD	8(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	16(SI), X1
	MULSD	32(DX), X1
	SUBSD	X1, X0
	MOVSD	24(SI), X1
	MULSD	40(DX), X1
	ADDSD	X1, X0
	MOVSD	32(SI), X1
	MULSD	16(DX), X1
	ADDSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	24(DX), X1
	SUBSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	56(DX), X1
	SUBSD	X1, X0
	MOVSD	56(SI), X1
	MULSD	48(DX), X1
	SUBSD	X1, X0
	MOVSD	X0, 8(R8)

	// out[2]
	MOVSD	0(SI), X0
	MULSD	16(DX), X0
	MOVSD	8(SI), X1
	MULSD	32(DX), X1
	ADDSD	X1, X0
	MOVSD	16(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	24(SI), X1
	MULSD	48(DX), X1
	SUBSD	X1, X0
	MOVSD	32(SI), X1
	MULSD	8(DX), X1
	SUBSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	56(DX), X1
	SUBSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	24(DX), X1
	ADDSD	X1, X0
	MOVSD	56(SI), X1
	MULSD	40(DX), X1
	SUBSD	X1, X0
	MOVSD	X0, 16(R8)

	// out[3]
	MOVSD	0(SI), X0
	MULSD	24(DX), X0
	MOVSD	8(SI), X1
	MULSD	40(DX), X1
	SUBSD	X1, X0
	MOVSD	16(SI), X1
	MULSD	48(DX), X1
	ADDSD	X1, X0
	MOVSD	24(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	32(SI), X1
	MULSD	56(DX), X1
	SUBSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	8(DX), X1
	ADDSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	16(DX), X1
	SUBSD	X1, X0
	MOVSD	56(SI), X1
	MULSD	32(DX), X1
	SUBSD	X1, X0
	MOVSD	X0, 24(R8)

	// out[4]
	MOVSD	0(SI), X0
	MULSD	32(DX), X0
	MOVSD	32(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	48(DX), X1
	ADDSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	40(DX), X1
	SUBSD	X1, X0
	MOVSD	X0, 32(R8)

	// out[5]
	MOVSD	0(SI), X0
	MULSD	40(DX), X0
	MOVSD	32(SI), X1
	MULSD	48(DX), X1
	SUBSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	32(DX), X1
	ADDSD	X1, X0
	MOVSD	X0, 40(R8)

	// out[6]
	MOVSD	0(SI), X0
	MULSD	48(DX), X0
	MOVSD	32(SI), X1
	MULSD	40(DX), X1
	ADDSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	32(DX), X1
	SUBSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	X0, 48(R8)

	// out[7]
	MOVSD	0(SI), X0
	MULSD	56(DX), X0
	MOVSD	8(SI), X1
	MULSD	48(DX), X1
	ADDSD	X1, X0
	MOVSD	16(SI), X1
	MULSD	40(DX), X1
	ADDSD	X1, X0
	MOVSD	24(SI), X1
	MULSD	32(DX), X1
	ADDSD	X1, X0
	MOVSD	32(SI), X1
	MULSD	24(DX), X1
	ADDSD	X1, X0
	MOVSD	40(SI), X1
	MULSD	16(DX), X1
	ADDSD	X1, X0
	MOVSD	48(SI), X1
	MULSD	8(DX), X1
	ADDSD	X1, X0
	MOVSD	56(SI), X1
	MULSD	0(DX), X1
	ADDSD	X1, X0
	MOVSD	X0, 56(R8)

	RET
