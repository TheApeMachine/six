//go:build arm64

#include "textflag.h"

// ============================================================================
// geometricFrame: ARM64 NEON-register PGA lane.
//
// func geometricFrame(value *uint64, opcode uint64) bool
//
// Frame layout:
//   Signals  word 32, byte 256: output multivector
//   Context  word 40, byte 320: left motor / operand
//   Gradient word 48, byte 384: right target / operand
//
// The sparse product keeps scalar FP dependency order inside SIMD registers.
// Reverse/sign-flip phases use packed NEON XOR lanes.
// ============================================================================
TEXT ·geometricFrame(SB), NOSPLIT|NOFRAME, $0-17
	MOVD	value+0(FP), R0
	MOVD	opcode+8(FP), R1
	MOVD	R30, R27

	AND	$0xF0, R1, R1

	CMP	$0x10, R1
	BEQ	geom_compose

	CMP	$0x20, R1
	BEQ	geom_sandwich

	CMP	$0x30, R1
	BEQ	geom_reverse

	MOVD	$0, R1
	MOVB	R1, ret+16(FP)
	MOVD	R27, R30
	RET

geom_compose:
	FMOVD	320(R0), F0
	FMOVD	328(R0), F1
	FMOVD	336(R0), F2
	FMOVD	344(R0), F3
	FMOVD	352(R0), F4
	FMOVD	360(R0), F5
	FMOVD	368(R0), F6
	FMOVD	376(R0), F7

	FMOVD	384(R0), F8
	FMOVD	392(R0), F9
	FMOVD	400(R0), F10
	FMOVD	408(R0), F11
	FMOVD	416(R0), F12
	FMOVD	424(R0), F13
	FMOVD	432(R0), F14
	FMOVD	440(R0), F15

	ADD	$256, R0, R3
	BL	geom_product_store

	MOVD	$1, R1
	MOVB	R1, ret+16(FP)
	MOVD	R27, R30
	RET

geom_sandwich:
	FMOVD	320(R0), F0
	FMOVD	328(R0), F1
	FMOVD	336(R0), F2
	FMOVD	344(R0), F3
	FMOVD	352(R0), F4
	FMOVD	360(R0), F5
	FMOVD	368(R0), F6
	FMOVD	376(R0), F7

	FMOVD	384(R0), F8
	FMOVD	392(R0), F9
	FMOVD	400(R0), F10
	FMOVD	408(R0), F11
	FMOVD	416(R0), F12
	FMOVD	424(R0), F13
	FMOVD	432(R0), F14
	FMOVD	440(R0), F15

	ADD	$256, R0, R3
	BL	geom_product_store

	FMOVD	256(R0), F0
	FMOVD	264(R0), F1
	FMOVD	272(R0), F2
	FMOVD	280(R0), F3
	FMOVD	288(R0), F4
	FMOVD	296(R0), F5
	FMOVD	304(R0), F6
	FMOVD	312(R0), F7

	FMOVD	384(R0), F8
	FMOVD	392(R0), F9
	FMOVD	400(R0), F10
	FMOVD	408(R0), F11
	FMOVD	416(R0), F12
	FMOVD	424(R0), F13
	FMOVD	432(R0), F14
	FMOVD	440(R0), F15

	FNEGD	F9, F9
	FNEGD	F10, F10
	FNEGD	F11, F11
	FNEGD	F12, F12
	FNEGD	F13, F13
	FNEGD	F14, F14

	ADD	$256, R0, R3
	BL	geom_product_store

	MOVD	$1, R1
	MOVB	R1, ret+16(FP)
	MOVD	R27, R30
	RET

geom_reverse:
	MOVD	$0x8000000000000000, R2
	MOVD	$0, R3
	VMOV	R3, V30.D[0]
	VMOV	R2, V30.D[1]
	VMOV	R2, V31.D[0]
	VMOV	R2, V31.D[1]
	VMOV	R2, V29.D[0]
	VMOV	R3, V29.D[1]

	ADD	$320, R0, R4
	ADD	$256, R0, R5

	VLD1	(R4), [V16.D2]
	VEOR	V30.B16, V16.B16, V16.B16
	VST1	[V16.D2], (R5)

	ADD	$16, R4, R4
	ADD	$16, R5, R5
	VLD1	(R4), [V16.D2]
	VEOR	V31.B16, V16.B16, V16.B16
	VST1	[V16.D2], (R5)

	ADD	$16, R4, R4
	ADD	$16, R5, R5
	VLD1	(R4), [V16.D2]
	VEOR	V31.B16, V16.B16, V16.B16
	VST1	[V16.D2], (R5)

	ADD	$16, R4, R4
	ADD	$16, R5, R5
	VLD1	(R4), [V16.D2]
	VEOR	V29.B16, V16.B16, V16.B16
	VST1	[V16.D2], (R5)

	MOVD	$1, R1
	MOVB	R1, ret+16(FP)
	MOVD	R27, R30
	RET

geom_product_store:
	// out[0] = l0*r0 - l4*r4 - l5*r5 - l6*r6
	FMULD	F8, F0, F16
	FMULD	F12, F4, F17
	FSUBD	F17, F16, F16
	FMULD	F13, F5, F17
	FSUBD	F17, F16, F16
	FMULD	F14, F6, F17
	FSUBD	F17, F16, F16
	FMOVD	F16, 0(R3)

	// out[1]
	FMULD	F9, F0, F16
	FMULD	F8, F1, F17
	FADDD	F17, F16, F16
	FMULD	F12, F2, F17
	FSUBD	F17, F16, F16
	FMULD	F13, F3, F17
	FADDD	F17, F16, F16
	FMULD	F10, F4, F17
	FADDD	F17, F16, F16
	FMULD	F11, F5, F17
	FSUBD	F17, F16, F16
	FMULD	F15, F6, F17
	FSUBD	F17, F16, F16
	FMULD	F14, F7, F17
	FSUBD	F17, F16, F16
	FMOVD	F16, 8(R3)

	// out[2]
	FMULD	F10, F0, F16
	FMULD	F12, F1, F17
	FADDD	F17, F16, F16
	FMULD	F8, F2, F17
	FADDD	F17, F16, F16
	FMULD	F14, F3, F17
	FSUBD	F17, F16, F16
	FMULD	F9, F4, F17
	FSUBD	F17, F16, F16
	FMULD	F15, F5, F17
	FSUBD	F17, F16, F16
	FMULD	F11, F6, F17
	FADDD	F17, F16, F16
	FMULD	F13, F7, F17
	FSUBD	F17, F16, F16
	FMOVD	F16, 16(R3)

	// out[3]
	FMULD	F11, F0, F16
	FMULD	F13, F1, F17
	FSUBD	F17, F16, F16
	FMULD	F14, F2, F17
	FADDD	F17, F16, F16
	FMULD	F8, F3, F17
	FADDD	F17, F16, F16
	FMULD	F15, F4, F17
	FSUBD	F17, F16, F16
	FMULD	F9, F5, F17
	FADDD	F17, F16, F16
	FMULD	F10, F6, F17
	FSUBD	F17, F16, F16
	FMULD	F12, F7, F17
	FSUBD	F17, F16, F16
	FMOVD	F16, 24(R3)

	// out[4]
	FMULD	F12, F0, F16
	FMULD	F8, F4, F17
	FADDD	F17, F16, F16
	FMULD	F14, F5, F17
	FADDD	F17, F16, F16
	FMULD	F13, F6, F17
	FSUBD	F17, F16, F16
	FMOVD	F16, 32(R3)

	// out[5]
	FMULD	F13, F0, F16
	FMULD	F14, F4, F17
	FSUBD	F17, F16, F16
	FMULD	F8, F5, F17
	FADDD	F17, F16, F16
	FMULD	F12, F6, F17
	FADDD	F17, F16, F16
	FMOVD	F16, 40(R3)

	// out[6]
	FMULD	F14, F0, F16
	FMULD	F13, F4, F17
	FADDD	F17, F16, F16
	FMULD	F12, F5, F17
	FSUBD	F17, F16, F16
	FMULD	F8, F6, F17
	FADDD	F17, F16, F16
	FMOVD	F16, 48(R3)

	// out[7]
	FMULD	F15, F0, F16
	FMULD	F14, F1, F17
	FADDD	F17, F16, F16
	FMULD	F13, F2, F17
	FADDD	F17, F16, F16
	FMULD	F12, F3, F17
	FADDD	F17, F16, F16
	FMULD	F11, F4, F17
	FADDD	F17, F16, F16
	FMULD	F10, F5, F17
	FADDD	F17, F16, F16
	FMULD	F9, F6, F17
	FADDD	F17, F16, F16
	FMULD	F8, F7, F17
	FADDD	F17, F16, F16
	FMOVD	F16, 56(R3)

	RET
