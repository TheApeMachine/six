//go:build ignore
// +build ignore

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/viper"
)

func main() {
	viper.SetConfigFile("../../cmd/cfg/config.yml")
	if err := viper.ReadInConfig(); err != nil {
		fmt.Printf("Error reading config: %v\n", err)
		os.Exit(1)
	}

	var content strings.Builder
	content.WriteString("// THIS FILE IS AUTOMATICALLY GENERATED BY go generate.\n")
	content.WriteString("// DO NOT EDIT. Source of truth: cmd/cfg/config.yml\n\n")
	content.WriteString("#ifndef SUBSTRATE_PRIMITIVES_H\n")
	content.WriteString("#define SUBSTRATE_PRIMITIVES_H\n\n")

	writeMacro(&content, "WORDS", viper.GetInt("value.words"))
	writeMacro(&content, "REG_PC", viper.GetInt("value.region.registers.pc"))
	writeMacro(&content, "PROGRAM_INDEX_WORD", viper.GetInt("value.region.program.start"))
	writeMacro(&content, "MAX_PC", int(viper.GetUint64("value.region.program.bits") / 32))

	content.WriteString("\n#endif // SUBSTRATE_PRIMITIVES_H\n")

	targetDir := "../../pkg/compute/kernel/shared"
	if err := os.MkdirAll(targetDir, 0755); err != nil {
		fmt.Printf("Error creating directory: %v\n", err)
		os.Exit(1)
	}

	targetPath := filepath.Join(targetDir, "primitives.h")
	if err := os.WriteFile(targetPath, []byte(content.String()), 0644); err != nil {
		fmt.Printf("Error creating header: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s\n", targetPath)
}

func writeMacro(b *strings.Builder, name string, val int) {
	fmt.Fprintf(b, "#define %-40s %d\n", name, val)
}
