package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

/*
gen.go generates a C header from value.go by parsing the AST and evaluating
constant expressions. No manual list — constants are discovered automatically.

Run: go generate ./pkg/primitive/...
*/
func main() {
	fset := token.NewFileSet()
	node, err := parser.ParseFile(fset, "value.go", nil, parser.ParseComments)
	if err != nil {
		fmt.Printf("Error parsing value.go: %v\n", err)
		os.Exit(1)
	}

	// Collect all constants with their resolved values.
	// We resolve simple integer literals and basic arithmetic expressions.
	consts := map[string]int64{}
	var order []string

	for _, decl := range node.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.CONST {
			continue
		}

		for _, spec := range genDecl.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}

			for i, name := range vs.Names {
				if !name.IsExported() {
					continue
				}

				if i < len(vs.Values) {
					if val, ok := evalExpr(vs.Values[i], consts); ok {
						consts[name.Name] = val
						order = append(order, name.Name)
					}
				}
			}
		}
	}

	var content strings.Builder
	content.WriteString("// THIS FILE IS AUTOMATICALLY GENERATED BY go generate.\n")
	content.WriteString("// DO NOT EDIT. Source of truth: pkg/primitive/value.go\n\n")
	content.WriteString("#ifndef SUBSTRATE_PRIMITIVES_H\n")
	content.WriteString("#define SUBSTRATE_PRIMITIVES_H\n\n")

	for _, name := range order {
		macro := toUpperSnake(name)
		fmt.Fprintf(&content, "#define %-40s %d\n", macro, consts[name])
	}

	content.WriteString("\n#endif // SUBSTRATE_PRIMITIVES_H\n")

	targetDir := "../../pkg/compute/kernel/shared"
	if err := os.MkdirAll(targetDir, 0755); err != nil {
		fmt.Printf("Error creating directory: %v\n", err)
		os.Exit(1)
	}

	targetPath := filepath.Join(targetDir, "primitives.h")
	if err := os.WriteFile(targetPath, []byte(content.String()), 0644); err != nil {
		fmt.Printf("Error creating header: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s with %d constants\n", targetPath, len(order))
}

// evalExpr resolves simple constant expressions: literals, identifiers, +, -, *, /
func evalExpr(expr ast.Expr, known map[string]int64) (int64, bool) {
	switch e := expr.(type) {
	case *ast.BasicLit:
		if e.Kind == token.INT {
			v, err := strconv.ParseInt(e.Value, 0, 64)
			return v, err == nil
		}
	case *ast.Ident:
		if v, ok := known[e.Name]; ok {
			return v, true
		}
	case *ast.BinaryExpr:
		l, lok := evalExpr(e.X, known)
		r, rok := evalExpr(e.Y, known)
		if lok && rok {
			switch e.Op {
			case token.ADD:
				return l + r, true
			case token.SUB:
				return l - r, true
			case token.MUL:
				return l * r, true
			case token.QUO:
				if r != 0 { return l / r, true }
			}
		}
	case *ast.ParenExpr:
		return evalExpr(e.X, known)
	case *ast.UnaryExpr:
		v, ok := evalExpr(e.X, known)
		if ok && e.Op == token.SUB {
			return -v, true
		}
	}
	return 0, false
}

func toUpperSnake(s string) string {
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}
		if r >= 'a' && r <= 'z' {
			result.WriteByte(byte(r - 'a' + 'A'))
		} else {
			result.WriteRune(r)
		}
	}
	return result.String()
}
